# 真实链条演练（云端）：prepare_r2f → r2f_engine.py → 假 Mplus（复制 Round2E 合成冒烟输出并回显收敛准则）→ read_result_r2f → 精确LL。
# 用法：Rscript r2f_chain_test.R <新建的 R2F 根目录>；环境变量 R2F_R2E、R2F_R2D、R2F_PY、R2F_MPLUS(=fake_mplus.py)、FAKE_R2E。
# 演练根目录的合同把 SMOKE 上限改为 5（只在这个一次性根目录里改），使第 6 次调用用于检验类别上限。
cf <- file.path(Sys.getenv('R2F_ROOT'), 'contracts/RUN_CONTRACT_2F.json'); cj <- jsonlite::fromJSON(cf, simplifyVector = FALSE)
cj$budget$categories$SMOKE <- 5L; jsonlite::write_json(cj, cf, auto_unbox = TRUE, pretty = TRUE, digits = NA)
source(file.path(Sys.getenv('R2F_ROOT'), 'code/r2f_local.R'), local = globalenv())
res <- list(); chk <- function(name, ok, detail = '') res[[length(res) + 1L]] <<- data.frame(test = name, result = if (isTRUE(ok)) 'PASS' else 'FAIL', detail = paste(detail, collapse = ' '))
syn <- r2e_model(C2F$round2E_inputs$SYN_E1B$id); data <- file.path(syn, 'data.dat')
wj(list(start_epoch = as.numeric(Sys.time())), file.path(ROOT, 'runtime/batch_window.json'))
common <- list(z = 'SD', sample = 'SYNTHETIC', source_data = data, ctrl = C2F$data$synthetic_ctrl, points = 15L, source_dir = syn)
go <- function(sp, attempt, ...) do.call(run_r2f, c(list(sp, 1L, attempt, 'SMOKE'), common, list(...)))
a <- go('E1B', 'chain_tight', conv = 'tight')
chk('tight_usable', usable(a), a$status)
chk('tight_criteria', isTRUE(a$criteria_as_requested) && identical(a$convergence$loglik_change, '0.100D-04') && identical(a$convergence$relative_change, '0.100D-08'))
chk('tight_exact_ll', abs(a$exact_LL_difference) < 1e-3 && isTRUE(a$exact_LL_n_match), a$exact_LL_difference)
chk('receipt_fields', identical(a$round, 'Round2F') && identical(a$keep_awake, 'NOT_WINDOWS') && a$gap_seconds == 0 && a$parameters == 50L && a$sy == 0)
inp <- readLines(file.path(a$dest, 'model.inp'))
chk('inp_has_tight_and_start_mapping', any(grepl('LOGCRITERION=0.00001; RLOGCRITERION=0.000000001;', inp, fixed = TRUE)) && any(grepl('^sy@0;$', inp)) &&
      all(utils::read.csv(file.path(a$dest, 'start_mapping.csv'))$action == 'mapped_high_precision'))
b <- go('E1B', 'chain_ml', conv = 'tight', estimator = 'ML', cluster = FALSE)
chk('ml_nocluster_usable', usable(b) && !any(grepl('CLUSTER', readLines(file.path(b$dest, 'model.inp')))), b$status)
c1 <- go('E1', 'chain_free', conv = 'tight', start_override = C2F$allowed_start_override)
mp <- utils::read.csv(file.path(c1$dest, 'start_mapping.csv'))
chk('free_from_E1B_override', usable(c1) && mp$value[mp$key == 'VAR:SY:'] == 0.02 && c1$parameters == 51L, c1$status)
chk('numeric_check_runs', isTRUE(numeric_check(a, b, 'start')$outcome == 'STRUCTURE_MISMATCH'))   # ML 无聚类与 MLR 聚类结构签名不同，按设计不比较
Sys.setenv(FAKE_MODE = 'ignore_criteria'); d <- go('E1B', 'chain_ignored', conv = 'tight'); Sys.setenv(FAKE_MODE = '')
chk('criteria_not_applied_detected', identical(d$status, 'CRITERIA_NOT_APPLIED'), d$status)
Sys.setenv(FAKE_MODE = 'reject'); e <- go('E1B', 'chain_reject', conv = 'tight'); Sys.setenv(FAKE_MODE = '')
chk('input_rejected_detected', identical(e$status, 'INPUT_REJECTED'), e$status)
f <- go('E1B', 'chain_capped', conv = 'tight')
chk('category_cap_not_run', identical(f$status, 'NOT_RUN_CATEGORY_CAP') && !dir.exists(file.path(ROOT, 'models', 'SYNTHETIC_SD_E1B_01_chain_capped')), f$status)
again <- go('E1B', 'chain_tight', conv = 'tight')
chk('idempotent_rerun', identical(again$output_sha256, a$output_sha256) && budget_r2f()$calls == 5L)
out <- do.call(rbind, res); utils::write.csv(out, file.path(ROOT, 'chain_results.csv'), row.names = FALSE)
cat(sprintf('%-36s %s %s\n', out$test, out$result, out$detail), sep = '')
cat('CHAIN_2F', if (all(out$result == 'PASS')) 'PASSED' else 'FAILED', nrow(out), '\n')
